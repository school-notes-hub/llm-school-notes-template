"""`sn book <t> <subject> <book-code> [<source>] [--offset N]` (plan 2.2, 3.2): a converted
textbook into `references/<subject>/<book-code>/` with a README table and the map.

With `<source>` (a doc-extract folder: `document.md`, `manifest.json`, `provenance.json`,
`figures/`): the files are copied (the original PDF/Office file stays out), a README is
written with the printed-page offset and a table made from the book's own table of contents,
and the map (`index.md`) is generated by the learner repo's `tools/book_index.py`. A writer
then checks the README table against the contents. Without `<source>`: only the map is
generated again from the (checked) README. `references/` is private; nothing is published."""

import subprocess
import sys
from pathlib import Path

from ..sources.naming import slug
from ..sources.toolload import load_tool
from ..state import safefs
from . import tool_writes
from .common import Refused

ORIGINALS = (".pdf", ".pptx", ".ppt", ".docx", ".doc")


def readme(code: str, offset: int, rows) -> str:
    lines = [f"# {code}", "", f"printed-page offset: {offset}", "", "<!-- book-index: readme -->", "",
             "| Lecke vagy rész | Nyomtatott kezdőoldal |", "|---|---|"]
    lines += [f"| {name} | {start} |" for name, start, _ in rows if start is not None]
    return "\n".join(lines) + "\n"


def place(repo: Path, rel: str, source: Path, code: str, offset: int) -> list[str]:
    if safefs.exists(repo, rel):
        raise Refused(f"{rel} már létezik; a térkép újragenerálása: sn book <tanuló> <tantárgy> <kód>")
    if not (source / "document.md").is_file():
        raise Refused(f"{source}: nincs document.md (doc-extract mappa kell)")
    written = []
    for path in sorted(p for p in source.rglob("*") if p.is_file()):
        if path.suffix.lower() in ORIGINALS:
            continue
        target = f"{rel}/{path.relative_to(source).as_posix()}"
        safefs.copy_in(path, repo, target)
        written.append(target)
    if not safefs.is_file(repo, f"{rel}/README.md"):
        tool = load_tool("book_index", repo / "tools")
        rows = tool.toc_rows(safefs.read_text(repo, f"{rel}/document.md").split("\n"))
        safefs.write_text(repo, f"{rel}/README.md", readme(code, offset, rows))
        written.append(f"{rel}/README.md")
    return written


def run(local, subject: str, code: str, source: Path | None, offset: int | None) -> int:
    repo = local.repo
    rel = f"references/{slug(subject)}/{slug(code)}"
    if source is not None:
        if offset is None:
            raise Refused("új könyvhöz kell az --offset N (nyomtatott oldal = PDF-oldal - N)")
        written = place(repo, rel, source, code, offset)
        print(f"elhelyezve: {rel} ({len(written)} fájl)")
    elif not safefs.is_file(repo, f"{rel}/README.md"):
        raise Refused(f"{rel}/README.md nincs meg")
    else:
        written = []
    argv = [sys.executable, "tools/book_index.py", rel] + (["--offset", str(offset)] if offset is not None and source is None else [])
    proc = subprocess.run(argv, cwd=repo, capture_output=True, text=True, timeout=300)
    print(proc.stdout.strip() or proc.stderr.strip())
    if proc.returncode == 0:      # the writer guard accepts exactly what this run wrote
        tool_writes.record(repo, files=written + [f"{rel}/index.md"])
    local.record("book", "ok" if proc.returncode == 0 else "error", target=rel)
    return proc.returncode
